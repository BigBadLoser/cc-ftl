#!/usr/bin/env node
/* global process, console */
// Rewrites tools/testWeights.ts (seconds per test file) from a Vitest JSON report, so the sequencer in vitest.sequencer.ts
// can start the longest files first and balance shards:
//   npx vitest run --reporter=json --outputFile=/tmp/vitest.json && node tools/testWeights.mjs /tmp/vitest.json
import { readFileSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';

const report = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const out = {};
for (const f of report.testResults) {
  const secs = Math.max(0.1, (f.endTime - f.startTime) / 1000);
  out[relative(process.cwd(), f.name)] = Math.round(secs * 10) / 10;
}
const sorted = Object.fromEntries(Object.entries(out).sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)));
writeFileSync(resolve('tools/testWeights.ts'), `// Generated by tools/testWeights.mjs (npm run test:weights): seconds per test file, used by vitest.sequencer.ts.\nexport default ${JSON.stringify(sorted, null, 1)} as Record<string, number>;\n`);
console.log(`wrote ${Object.keys(sorted).length} weights`);
