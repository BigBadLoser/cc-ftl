import type { Sim } from '../sim';
import { claimGeneration, provideGenerated, releaseGeneration } from '../sim/galaxy/arrivals';
import { warmCandidates } from '../sim/galaxy/fleetShips';
import type { Contact } from '../sim/galaxy/types';
import type { GenResult } from '../sim/shipgen/types';

/** Makes a ship the way `generateShip` does, somewhere that does not stall the frame (a worker). Null: it cannot be generated. */
export interface ShipGenerator {
  generate(job: { shipgen: string; seed: number; depth: number }): Promise<GenResult | null>;
}

/** How often the node is scanned for ships about to turn up. */
export const PREWARM_EVERY_MS = 500;

/**
 * Generates the ships of the fleets about to arrive (#388) off the main thread. The sim warms them itself, one a second, but
 * `generateShip` takes 30 to 120 ms, which is a hitch whenever it runs. Here every candidate is claimed (so the sim leaves it
 * alone) and generated by `gen`; the result goes into the sim's memo, so the ship arrives from there as before. Generation is a
 * pure function of the contact, so the ships are the same ones, and a ship needed before its result is in is still generated on
 * the spot. A failed job gives the claim back, and the sim warms that ship itself.
 */
export function createPrewarm(sim: Sim, gen: ShipGenerator, now: () => number): { update(): void } {
  let last = -Infinity;
  return {
    update() {
      const t = now();
      if (t - last < PREWARM_EVERY_MS) return;
      last = t;
      for (const c of warmCandidates(sim)) {
        if (!claimGeneration(sim, c)) continue;
        gen.generate({ shipgen: c.shipgen, seed: c.seed, depth: c.depth }).then(
          (g) => provideGenerated(sim, c as Contact, g),
          () => releaseGeneration(sim, c as Contact),
        );
      }
    },
  };
}
